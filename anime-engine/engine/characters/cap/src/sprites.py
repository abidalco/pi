"""Register the generated key drawings: same scale (silhouette area vs. idle), anchor (feet on the floor, or body centre
for airborne poses), facing right. Writes ../spr_<name>.png and the 'sprites' table into ../char.json + ../char.js."""
import json
from pathlib import Path
import numpy as np
from PIL import Image

HERE = Path(__file__).parent
P = HERE / "poses"
# name: (keyed file, anchor mode, mirror?, drawn rotation of the body in degrees)
SPRITES = {
    "idle": ("g1_0", "ground", 0, 0), "wave_a": ("g1_2", "ground", 0, 0), "wave_b": ("wave2", "ground", 0, 0),
    "talk_a": ("g1_3", "ground", 0, 0), "talk_b": ("g1_4", "ground", 0, 0), "point": ("g1_5", "ground", 0, 0),
    "crouch": ("g2_0", "ground", 0, 0), "launch": ("g2_1", "center", 0, 0), "fly": ("g2_2", "center", 0, 76),
    "brake": ("g2_3", "center", 0, 0), "land": ("g2_4", "ground", 0, 0), "land_look": ("landlook", "ground", 0, 0),
    "tuck": ("g3_0", "center", 0, 0), "stick": ("g3_1", "ground", 0, 0), "wobble": ("g3_2", "ground", 0, 0),
    "sit": ("g3_3", "ground", 1, 0), "sit_up": ("g3_4", "ground", 1, 0), "hop": ("g3_5", "center", 0, 0),
    # walk cycle, one step = contact → down → passing → up (legs read the same either side in black joggers)
    "walk_1": ("w_2", "ground", 0, 0), "walk_2": ("w_3", "ground", 0, 0), "walk_3": ("p_0", "ground", 0, 0), "walk_4": ("p_1", "ground", 0, 0),
}
# head height (cap top → beard bottom) measured on the measurement sheet, same px scale for every drawing.
# The drawings were generated at different zooms; the head is the one size that must match across all of them.
HEAD = {"g1_0": 43, "g1_2": 45, "wave2": 42, "g1_3": 44, "g1_4": 44, "g1_5": 42, "g2_0": 77, "g2_1": 26, "g2_2": 23,
        "g2_3": 33, "g2_4": 60, "landlook": 62, "g3_0": 60, "g3_1": 60, "g3_2": 60, "g3_3": 65, "g3_4": 65, "g3_5": 60, "w_2": 48.5, "w_3": 48.5, "p_0": 48, "p_1": 48}
# second pass from the lineup (films/_lineup): body proportions drift in some drawings (stretched limbs in flight)
FIX = {"g2_0": .98, "g2_1": .88, "g2_2": .62, "g2_3": .8, "g2_4": 1.2, "landlook": 1.2, "g3_2": .92, "g3_0": 1.05}
SCALE_OUT = .6                                   # stored resolution (character ≈ 1000 px tall)
CH = json.load(open(HERE.parent / "char.json"))


def load(f, mirror):
    im = Image.open(P / f"{f}_key.png")
    if mirror: im = im.transpose(Image.FLIP_LEFT_RIGHT)
    a = np.asarray(im).copy()
    if f.startswith("p_"):                       # cropped from a two-figure image: keep only the main figure
        from scipy import ndimage
        lab, n = ndimage.label(a[..., 3] > 24)
        if n > 1:
            sizes = ndimage.sum(np.ones_like(lab), lab, range(1, n + 1)); keep = int(np.argmax(sizes)) + 1
            a[..., 3] = np.where(ndimage.binary_dilation(lab == keep, iterations=2), a[..., 3], 0)
        im = Image.fromarray(a, "RGBA")
    ys, xs = np.where(a[..., 3] > 24)
    return im.crop((xs.min(), ys.min(), xs.max() + 1, ys.max() + 1))


ref = load("g1_0", 0)
ref_area = (np.asarray(ref)[..., 3] > 24).sum()
k_idle = 100 / ref.height                        # idle head-to-toe = 100 world units (matches the rig)
out = {}
for name, (f, mode, mirror, rot0) in SPRITES.items():
    if not (P / f"{f}_key.png").exists(): print("missing", f); continue
    im = load(f, mirror)
    a = np.asarray(im); m = a[..., 3] > 24
    ratio = (HEAD["g1_0"] / HEAD[f] if f in HEAD else float(np.clip(np.sqrt(ref_area / m.sum()), .82, 1.2))) * FIX.get(f, 1)
    k = k_idle * ratio
    if mode == "ground":
        band = m[int(im.height * .965):]
        ys, xs = np.where(band)
        ax, ay = float(xs.mean()), float(im.height)
    else:
        ys, xs = np.where(m); ax, ay = float(xs.mean()), float(ys.mean())
    small = im.resize((int(im.width * SCALE_OUT), int(im.height * SCALE_OUT)), Image.LANCZOS)
    small.save(HERE.parent / f"spr_{name}.png")
    out[name] = {"img": f"spr_{name}.png", "k": round(k / SCALE_OUT, 5), "anchor": [round(ax * SCALE_OUT, 1), round(ay * SCALE_OUT, 1)],
                 "mode": mode, "rot0": rot0}
    print(f"{name:10s} {f:9s} scale×{ratio:.2f} {mode}")
CH["sprites"] = out
json.dump(CH, open(HERE.parent / "char.json", "w"), indent=1)
open(HERE.parent / "char.js", "w").write("// generated by src/cut.py + faces.py + sprites.py — image-part character with key drawings\nregisterCharacter("
    + json.dumps(CH) + ', document.currentScript.src.replace(/char\\.js$/, ""));\n')
