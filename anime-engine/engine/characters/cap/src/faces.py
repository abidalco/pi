"""Cut expression heads from the faces sheet and register each one to the neutral head by its cap (same size/pivot)."""
import json
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage

HERE = Path(__file__).parent
CH = json.load(open(HERE.parent / "char.json"))
neutral = np.asarray(Image.open(HERE.parent / "head.png")).astype(np.float32)
sheet = np.asarray(Image.open(HERE / "faces_key.png")).astype(np.float32)


def cap_box(img, top_frac=.5):
    """bbox of the largest near-black blob in the upper part (the cap)"""
    h = int(img.shape[0] * top_frac)
    lum = img[:h, ..., :3].mean(-1)
    m = (lum < 42) & (img[:h, ..., 3] > 128)
    lab, n = ndimage.label(m)
    if not n: return None
    sizes = ndimage.sum(m, lab, range(1, n + 1)); k = int(np.argmax(sizes)) + 1
    ys, xs = np.where(lab == k)
    return np.array([xs.min(), ys.min(), xs.max(), ys.max()], float)


nb = cap_box(neutral)
hp = CH["parts"]["head"]
# neutral head outline (head.png px): the cut polygon from cut.py, shifted into the crop
x_off, y_off = 752 - hp["pivot"][0], 380 - hp["pivot"][1]
outline = np.array([(640, 70), (960, 70), (960, 420), (880, 418), (800, 400), (744, 388), (680, 372), (640, 366)], float) - [x_off, y_off]
CELLS = {"smile": (1, 0), "determined": (2, 0), "closed": (0, 1), "pant": (1, 1), "shout": (2, 1)}
faces = {}
for name, (cx, cy) in CELLS.items():
    cell = sheet[cy * 800:(cy + 1) * 800, cx * 600:(cx + 1) * 600]
    vb = cap_box(cell)
    s = (vb[2] - vb[0]) / (nb[2] - nb[0])                      # variant px per neutral px
    poly = (outline - nb[:2]) * s + vb[:2]
    m = Image.new("L", (cell.shape[1], cell.shape[0]), 0); ImageDraw.Draw(m).polygon([tuple(p) for p in poly], fill=255)
    a = cell.copy(); a[..., 3] *= np.asarray(m) / 255
    # resample into neutral scale so every head shares the neutral pivot geometry
    im = Image.fromarray(a.astype(np.uint8), "RGBA").resize((int(cell.shape[1] / s), int(cell.shape[0] / s)), Image.LANCZOS)
    piv = (np.array(hp["pivot"], float) - nb[:2]) * s + vb[:2]
    pv = piv / s
    arr = np.asarray(im); ys, xs = np.where(arr[..., 3] > 8)
    x0, y0, x1, y1 = int(xs.min()) - 2, int(ys.min()) - 2, int(xs.max()) + 3, int(ys.max()) + 3
    im.crop((x0, y0, x1, y1)).save(HERE.parent / f"face_{name}.png")
    p = [round(float(pv[0] - x0), 1), round(float(pv[1] - y0), 1)]
    faces[name] = {"img": f"face_{name}.png", "pivot": p, "to": [p[0], round(p[1] - (hp["pivot"][1] - hp["to"][1]), 1)]}
    print(name, "scale", round(s, 3), "pivot", p)
CH["faces"] = faces
json.dump(CH, open(HERE.parent / "char.json", "w"), indent=1)
open(HERE.parent / "char.js", "w").write("// generated by src/cut.py + src/faces.py — image-part character\nregisterCharacter("
    + json.dumps(CH) + ', document.currentScript.src.replace(/char\\.js$/, ""));\n')
# check strip: all heads on their pivots
ims = [("head", hp)] + [(f"face_{n}", f) for n, f in faces.items()]
strip = Image.new("RGBA", (len(ims) * 330, 420), (235, 225, 240, 255)); d = ImageDraw.Draw(strip)
for i, (fn, f) in enumerate(ims):
    im = Image.open(HERE.parent / f"{fn}.png"); ox, oy = i * 330 + 165 - f["pivot"][0], 390 - f["pivot"][1]
    strip.alpha_composite(im, (int(ox), int(oy))); d.ellipse([i * 330 + 160, 385, i * 330 + 170, 395], fill=(255, 0, 90, 255))
strip.convert("RGB").resize((len(ims) * 165, 210)).save("/private/tmp/claude-501/-Users-hadim-moodboard/1387714d-fb06-44f1-922b-d271741f8546/scratchpad/faces.jpg", quality=82)
